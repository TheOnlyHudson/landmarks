/** Metres the rock surface stands over the DEM it was read from, so the map's own rock never shows through. */
const ROCK_LIFT = 0.8
const Z2 = [0, 0]
function buildRock(r: Rock) {
  const ny = r.cells.length, nx = r.cells[0].length
  const on = (i: number, j: number) => i >= 0 && j >= 0 && i < nx && j < ny && r.cells[j][i] === '#'
  // The outline's vertices sit on the DEM (a little under it), so the rock rises out of the map's ground
  // with no wall at its foot; inside, it stands on the envelope of the DEM.
  const edge = (i: number, j: number) => !(on(i - 1, j - 1) && on(i, j - 1) && on(i - 1, j) && on(i, j))
  // Where the outline crosses a steep spot (the envelope well over the DEM), it keeps its height and a
  // skirt drops from it to the ground, so the cliff stays covered.
  const steep = (i: number, j: number) => r.top[j][i] - r.dem[j][i] > 1.0
  const Zt = (i: number, j: number) => (edge(i, j) && !steep(i, j) ? r.dem[j][i] - 0.4 : r.top[j][i] + ROCK_LIFT)
  // Round the outline's 4 m staircase: a convex corner (one rock cell beside it) moves in toward that cell,
  // a concave one (three) out toward the gap, by up to 0.4 of a cell.
  const XYat = (i: number, j: number): [number, number] => {
    const x = r.x0 + i * r.step, y = r.y1 - j * r.step
    const cells = [[i - 1, j - 1], [i, j - 1], [i - 1, j], [i, j]].filter(([a, b]) => on(a, b))
    if (cells.length !== 1 && cells.length !== 3) return [x, y]
    let dx = 0, dy = 0
    for (const [a, b] of [[i - 1, j - 1], [i, j - 1], [i - 1, j], [i, j]]) {
      const w = on(a, b) ? 1 : -1, cx = r.x0 + (a + 0.5) * r.step, cy = r.y1 - (b + 0.5) * r.step
      dx += w * (cx - x), dy += w * (cy - y)
    }
    // (dx, dy) points into the rock either way: in toward a lone cell, or away from a lone gap
    const l = Math.hypot(dx, dy) || 1, k = (cells.length === 1 ? 0.4 : -0.4) * r.step
    return [x + (dx / l) * k, y + (dy / l) * k]
  }
  const P = (i: number, j: number): V3 => [...XYat(i, j), Zt(i, j)]
  // smooth normals from the surface's slope, so neighbouring cells share their corners
  const T = (i: number, j: number) => Zt(Math.max(0, Math.min(nx, i)), Math.max(0, Math.min(ny, j)))
  const N = (i: number, j: number): V3 => {
    const gx = (T(i + 1, j) - T(i - 1, j)) / (2 * r.step), gy = (T(i, j - 1) - T(i, j + 1)) / (2 * r.step)
    const l = Math.hypot(gx, gy, 1)
    return [Math.round((-gx / l) * 1000) / 1000, Math.round((-gy / l) * 1000) / 1000, Math.round((1 / l) * 1000) / 1000]
  }
  for (let j = 0; j < ny; j++)
    for (let i = 0; i < nx; i++) {
      if (!on(i, j)) continue
      const a = P(i, j + 1), b = P(i + 1, j + 1), c = P(i + 1, j), d = P(i, j)
      // split along the shorter diagonal in height, so ridges stay ridges
      const [na, nb, nc, nd] = [N(i, j + 1), N(i + 1, j + 1), N(i + 1, j), N(i, j)]
      if (Math.abs(a[2] - c[2]) < Math.abs(b[2] - d[2])) { rock.tri(a, b, c, Z2, Z2, Z2, [na, nb, nc]); rock.tri(a, c, d, Z2, Z2, Z2, [na, nc, nd]) }
      else { rock.tri(a, b, d, Z2, Z2, Z2, [na, nb, nd]); rock.tri(b, c, d, Z2, Z2, Z2, [nb, nc, nd]) }
      const skirt = (p: [number, number], q: [number, number]) => {
        if (!steep(...p) && !steep(...q)) return
        const F = (v: [number, number]): V3 => [...XYat(...v), r.dem[v[1]][v[0]] - 0.4]
        rock.quad(F(p), F(q), P(...q), P(...p))
      }
      if (!on(i, j + 1)) skirt([i, j + 1], [i + 1, j + 1]) // south side
      if (!on(i + 1, j)) skirt([i + 1, j + 1], [i + 1, j]) // east
      if (!on(i, j - 1)) skirt([i + 1, j], [i, j]) // north
      if (!on(i - 1, j)) skirt([i, j], [i, j + 1]) // west
    }
}
