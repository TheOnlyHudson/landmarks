/** Points along a ring's edges no more than `max` apart, so a base can follow the ground. */
function densify(ring: XY[], max = 4): XY[] {
  const out: XY[] = []
  ring.forEach((a, k) => {
    const b = ring[(k + 1) % ring.length]
    const n = Math.max(1, Math.ceil(Math.hypot(b[0] - a[0], b[1] - a[1]) / max))
    for (let s = 0; s < n; s++) out.push([a[0] + ((b[0] - a[0]) * s) / n, a[1] + ((b[1] - a[1]) * s) / n])
  })
  return out
}
/** Walls of a counter-clockwise ring from the ground (sunk 0.4 m) to `z1`, flat top in `top` with a chamfer. */
function footed(p: Part, ring: XY[], z1: number, top: Part | null = p, bev = 0.35) {
  const r = densify(ccw(ring))
  const n = r.length
  for (let k = 0; k < n; k++) {
    const a = r[k], b = r[(k + 1) % n]
    p.quad([a[0], a[1], ground(...a) - 0.4], [b[0], b[1], ground(...b) - 0.4], [b[0], b[1], z1 - bev], [a[0], a[1], z1 - bev])
  }
  const inner = offset(ccw(ring), -bev)
  const ro = ccw(ring)
  for (let k = 0; k < ro.length; k++) {
    const l = (k + 1) % ro.length
    p.quad([ro[k][0], ro[k][1], z1 - bev], [ro[l][0], ro[l][1], z1 - bev], [inner[l][0], inner[l][1], z1], [inner[k][0], inner[k][1], z1])
  }
  if (top) capPoly(top, inner, z1, true)
}
/** A closed prism between two heights (for things that stand off the ground). */
function slabRing(p: Part, ring: XY[], z0: number, z1: number, top: Part = p) {
  const r = ccw(ring)
  for (let k = 0; k < r.length; k++) {
    const a = r[k], b = r[(k + 1) % r.length]
    p.quad([a[0], a[1], z0], [b[0], b[1], z0], [b[0], b[1], z1], [a[0], a[1], z1])
  }
  capPoly(top, r, z1, true)
  capPoly(p, r, z0, false)
}
