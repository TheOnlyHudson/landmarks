const LNG = -84.51125, LAT = 39.09761, BEARING = 349
const F = framer(LNG, LAT, BEARING)

/** Plans, in the model frame (from OSM, copied in so the generator stands alone). */
type Plan = { id: string; h: number; ring: XY[] }

function loadPlans(): Plan[] {
  const want: Record<string, number> = {
    'way/30736346': 13.5,
    'way/313373010': 18, 'way/1457062092': 24, 'way/1457062089': 18,
    'way/1457063391': 0, 'way/1457064156': 0, 'way/1457065370': 0, 'way/1457065175': 0, 'way/1457064722': 0, 'way/1457064721': 0,
    'way/1457062091': 9, 'way/1457063729': 9, 'way/1457062093': 13.5, 'way/1457062094': 13.5, 'way/1457062090': 4.5,
  }
  return OSM
    .filter((b) => b.id in want)
    .map((b) => {
      const ring = ccw(b.coords.map((c) => F(c)))
      let h = want[b.id]
      if (h === 0) {
        // a travertine wall: as tall as the pavilion it flanks
        const cx = ring.reduce((s, p) => s + p[0], 0) / ring.length
        h = Math.abs(cx - 1) < 22 ? 24 : 18
      }
      return { id: b.id, h, ring: ring.map((p) => [round(p[0]), round(p[1])] as XY) }
    })
}
const round = (v: number) => Math.round(v * 100) / 100

/** Min and max x of a ring along the line at y. */
function span(r: XY[], y: number): [number, number] | undefined {
  const xs: number[] = []
  for (let i = 0; i < r.length; i++) {
    const a = r[i], b = r[(i + 1) % r.length]
    if ((a[1] <= y && b[1] > y) || (b[1] <= y && a[1] > y)) xs.push(a[0] + ((y - a[1]) / (b[1] - a[1])) * (b[0] - a[0]))
  }
  if (xs.length < 2) return undefined
  return [Math.min(...xs), Math.max(...xs)]
}

function build() {
  const trav = new Part(), copper = new Part(), win = new Part(), roof = new Part(), glass = new Part()
  const plans = loadPlans()
  const get = (id: string) => plans.find((p) => p.id === id)!
  const outline = get('way/30736346')
  const pavIds = ['way/313373010', 'way/1457062092', 'way/1457062089']
  const wallIds = ['way/1457063391', 'way/1457064156', 'way/1457065370', 'way/1457065175', 'way/1457064722', 'way/1457064721']
  const parts = plans.filter((p) => p !== outline)

  // ---- the glazed bridges: the outline at 13.5 m, walls drawn only where no part stands
  {
    const r = outline.ring
    for (let i = 0; i < r.length; i++) {
      const a = r[i], b = r[(i + 1) % r.length], n = outward(a, b)
      const m: XY = [(a[0] + b[0]) / 2 - n[0] * 0.3, (a[1] + b[1]) / 2 - n[1] * 0.3]
      if (parts.some((p) => inside(m, p.ring))) continue
      wallEdge(win, r, i, 0, outline.h, 0)
      // a pale floor slab line across each bridge front, every storey
      for (const z of [4.4, 8.9]) wallSlab(trav, a, b, n, z)
      wallSlab(trav, a, b, n, outline.h - 0.9)
    }
    capRing(roof, r, outline.h)
  }

  // ---- travertine walls, low blocks
  for (const p of parts) {
    if (pavIds.includes(p.id)) continue
    const isWall = wallIds.includes(p.id)
    const mat = p.id === 'way/1457062093' || p.id === 'way/1457062094' ? win : trav
    for (let i = 0; i < p.ring.length; i++) wallEdge(mat, p.ring, i, 0, p.h, isWall ? 35 : 0)
    capRing(isWall ? trav : roof, p.ring, p.h)
  }
  // the middle's entrance block is a glass front under a travertine lintel
  {
    const p = get('way/1457062091'), r = p.ring
    for (let i = 0; i < r.length; i++) {
      const a = r[i], b = r[(i + 1) % r.length], n = outward(a, b)
      if (n[1] < -0.7) flush(glass, a, b, n, 0.4, 7.2)
    }
  }

  // ---- the copper pavilions with rolled roofs
  const RISE = 2.5
  for (const id of pavIds) {
    const p = get(id), r = p.ring
    const ys = r.map((q) => q[1]), y0 = Math.min(...ys), y1 = Math.max(...ys), yc = (y0 + y1) / 2, hy = (y1 - y0) / 2
    const eave = p.h - RISE
    const Z = (y: number) => eave + RISE * Math.sqrt(Math.max(0, 1 - ((y - yc) / hy) ** 2))
    for (let i = 0; i < r.length; i++) {
      const a = r[i], b = r[(i + 1) % r.length], n = outward(a, b)
      const A0: V3 = [a[0], a[1], 0], B0: V3 = [b[0], b[1], 0], B1: V3 = [b[0], b[1], Z(b[1])], A1: V3 = [a[0], a[1], Z(a[1])]
      copper.quad(A0, B0, B1, A1)
      void n
    }
    // the roof: strips across the plan at every vertex height and along the roll
    const rows = [...new Set([...ys, ...Array.from({ length: 13 }, (_, k) => y0 + ((y1 - y0) * k) / 12)])].sort((u, v) => u - v)
      .map((y) => Math.min(y1 - 0.01, Math.max(y0 + 0.01, y)))
    let prev: [number, number, number] | undefined
    for (const y of rows) {
      const s = span(r, y)
      if (!s) continue
      const cur: [number, number, number] = [s[0], s[1], y]
      if (prev && cur[2] - prev[2] > 0.05)
        copper.quad([prev[0], prev[2], Z(prev[2])], [prev[1], prev[2], Z(prev[2])], [cur[1], cur[2], Z(cur[2])], [cur[0], cur[2], Z(cur[2])])
      prev = cur
    }
    // windows: the south and north faces
    for (let i = 0; i < r.length; i++) {
      const a = r[i], b = r[(i + 1) % r.length], n = outward(a, b), L = Math.hypot(b[0] - a[0], b[1] - a[1])
      if (L < 12 || Math.abs(n[1]) < 0.9) continue
      const t: XY = [(b[0] - a[0]) / L, (b[1] - a[1]) / L]
      const at = (u: number): XY => [a[0] + t[0] * u, a[1] + t[1] * u]
      if (id === 'way/1457062092') {
        // two rows of six square windows high in the copper
        for (const z of [17.4, 20.2]) for (let k = 0; k < 6; k++) {
          const u = L / 2 + (k - 2.5) * 3.6
          flush(win, at(u - 0.8), at(u + 0.8), n, z, z + 1.6)
        }
        // the glass front over the entrance block (south only)
        if (n[1] < 0) flush(win, at(L * 0.12), at(L * 0.88), n, 9, 13)
      } else if (n[1] < 0) {
        // a broad window low in the river face (Lanser: west 0.2-0.6, east 0.05-0.35 of the face)
        const west = id === 'way/313373010'
        const u0 = west ? L * 0.2 : L * 0.05, u1 = west ? L * 0.6 : L * 0.35
        flush(win, at(u0), at(u1), n, 1.2, 6.5)
      }
    }
  }

  return finishGlb('National Underground Railroad Freedom Center', [
    { part: trav, material: finish('travertine', 0xe8dcc6) },
    { part: copper, material: finish('freedom-copper', 0x9a6450) },
    { part: win, material: PALETTE.window },
    { part: glass, material: finish('entrance', 0x6c7f8f, 0.4) },
    { part: roof, material: PALETTE.roof },
  ], { bearing: BEARING, height: 24, replaces: REPLACES })
}

/** A flat panel over segment a-b, 0.06 m off the wall, z0..z1. */
function flush(part: Part, a: XY, b: XY, n: XY, z0: number, z1: number) {
  const A: XY = [a[0] + n[0] * 0.06, a[1] + n[1] * 0.06], B: XY = [b[0] + n[0] * 0.06, b[1] + n[1] * 0.06]
  part.quad([A[0], A[1], z0], [B[0], B[1], z0], [B[0], B[1], z1], [A[0], A[1], z1])
}
/** A thin pale slab band across a glazed bridge front. */
function wallSlab(part: Part, a: XY, b: XY, n: XY, z: number) {
  flush(part, a, b, n, z, z + 0.7)
}

